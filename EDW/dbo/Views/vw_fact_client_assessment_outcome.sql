
create  view [dbo].[vw_fact_client_assessment_outcome]

as

SELECT  [fact_client_assessment_outcome_key]
      ,[fact_client_assessment_outcome_unique_key]
      ,f.[dim_client_key]
	  ,isnull(dc.[dim_client_key], CASE 
			WHEN f.client_id IS NOT NULL
				THEN - 1
			ELSE 0
			END) AS [dim_client_key_latest]
      ,[dim_client_referral_key]
      ,[dim_client_team_key]
      ,[dim_company_key]
      ,f.[client_id]
      ,[client_referral_id]
      ,[client_team_id]
      ,[client_outcome_tool_title]
      ,[assessment_id]
      ,[response_created_date]
	  ,cast(convert(nvarchar(8), f.[response_created_date], 112) as Int) as response_created_date_key

      ,[assessment_completed_by]
      ,[client_team_name]
      ,[Q1]
      ,[Q2]
      ,[Q3]
      ,[Q4]
      ,[Q5]
      ,[Q6]
      ,[Q7]
      ,[Q8]
      ,[Q9]
      ,[Q10]
      ,[Q11]
      ,[Q12]
      ,[Q1A]
      ,[Q1B]
      ,[Q1C]
      ,[Q1D]
      ,[Q2A]
      ,[Q2B]
      ,[Q2C]
      ,[Q2D]
      ,[Q3A]
      ,[Q3B]
      ,[Q3C]
      ,[Q3D]
      ,[Q4A]
      ,[Q4B]
      ,[Q4C]
      ,[Q4D]
      ,[total_score]
      ,[avg_score]
      ,[avg_score_HOP]
      ,[HOPQ1]
      ,[HOPQ2]
      ,[HOPQ3]
      ,[HOPQ4]
      ,[row_count]
      ,[row_count_desc]
      ,[row_count_ref]
      ,[row_count_ref_desc]
      ,f.[DWHBatchId]
      ,f.[DWHEffectiveFrom]
      ,f.[DWHEffectiveTo]
      ,f.[DWHDMLOperation]
      ,f.[DWHIsCurrent]
      ,f.[DWHSourceSystem]
  FROM [edw].[fact_client_assessment_outcome] f
  left join [edw].[dim_client] dc ON f.client_id = dc.client_id
	and f.dim_company_key = dc.[company_id]
	and dc.DWHIsCurrent = 1